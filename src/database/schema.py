def _preflight_existing_strict_storage(db: BaseDatabase) -> None:
    """Reject unsafe SE/WE/JC identities before unrelated additive migration."""

    from src.database.migration import _migration_targets
    from src.importer.importer import (
        verify_jc_storage_schema,
        verify_se_storage_schema,
        verify_we_storage_schema,
    )

    targets = _migration_targets(db)
    for target in targets:
        for table_name in STRICT_SE_STORAGE_TABLES:
            if target.table_exists_strict(table_name):
                verify_se_storage_schema(
                    target,
                    table_name,
                    allow_missing_columns=True,
                )
        for table_name in STRICT_WE_STORAGE_TABLES:
            if target.table_exists_strict(table_name):
                verify_we_storage_schema(target, table_name)
        for table_name in STRICT_JC_STORAGE_TABLES:
            if target.table_exists_strict(table_name):
                verify_jc_storage_schema(target, table_name)


def _normalize_metadata_catalog_type(declared_type: str) -> str | None:
    """Normalize backend catalog types to the public MCP type families."""

    normalized = re.sub(r"\s+", " ", str(declared_type or "").strip().upper())
    token = normalized.split("(", 1)[0].split(" ", 1)[0]
    if token in {"CHAR", "CHARACTER", "CLOB", "NCHAR", "NVARCHAR", "TEXT", "VARCHAR"}:
        return "TEXT"
    if token in {"DATE", "DATETIME", "TIME", "TIMESTAMP"}:
        return "TEXT"
    if token in {"BIGINT", "INT8"}:
        return "BIGINT"
    if token in {"INT", "INT2", "INT4", "INTEGER", "SMALLINT"}:
        return "INTEGER"
    if token in {"DECIMAL", "DOUBLE", "FLOAT", "NUMERIC", "REAL"}:
        return "REAL"
    return None


class SchemaManager:
    """Schema management for JLTSQL database.

    Manages table creation and schema operations.
    """

    def __init__(self, db: BaseDatabase):
        """Initialize schema manager.

        Args:
            db: Database instance
        """
        self.db = db

    def get_table_names(self) -> List[str]:
        """Get list of all table names in schema.

        Returns:
            List of table names
        """
        return list(SCHEMAS.keys())

    def create_table(self, table_name: str) -> bool:
        """Additively migrate and create a single table.

        Args:
            table_name: Name of table to create

        Returns:
            True if successful, False otherwise
        """
        if table_name not in SCHEMAS:
            logger.error(f"Unknown table: {table_name}")
            return False

        try:
            from src.database.migration import (
                migrate_table_if_needed,
                verify_table_schema,
            )

            schema_sql = SCHEMAS[table_name]
            _preflight_existing_strict_storage(self.db)
            if table_name not in STRICT_RECREATE_TABLES:
                migrate_table_if_needed(self.db, table_name, schema_sql)
            self.db.execute(schema_sql)
            verify_table_schema(self.db, table_name, schema_sql)
            if table_name in STRICT_SE_STORAGE_TABLES:
                from src.importer.importer import verify_se_storage_schema

                verify_se_storage_schema(self.db, table_name)
            if table_name in STRICT_WE_STORAGE_TABLES:
                from src.importer.importer import verify_we_storage_schema

                verify_we_storage_schema(self.db, table_name)
            if table_name in STRICT_JC_STORAGE_TABLES:
                from src.importer.importer import verify_jc_storage_schema

                verify_jc_storage_schema(self.db, table_name)
            if table_name in STRICT_RECREATE_TABLES:
                from src.importer.importer import verify_ck_child_table

                verify_ck_child_table(self.db, table_name)
            logger.info(f"Created table: {table_name}")
            return True
        except Exception as e:
            logger.error(f"Failed to create table {table_name}: {e}")
            return False

    def create_all_tables(self) -> Dict[str, bool]:
        """Additively migrate and create all tables defined in SCHEMAS.

        Returns:
            Dictionary mapping table names to success status
        """
        from src.database.migration import migrate_all_tables, verify_table_schema

        logger.info("Creating all tables...")
        try:
            _preflight_existing_strict_storage(self.db)
        except Exception as error:
            logger.error(f"Strict schema preflight failed before migration: {error}")
            return dict.fromkeys(SCHEMAS, False)
        migrate_all_tables(
            self.db,
            {
                table_name: schema_sql
                for table_name, schema_sql in SCHEMAS.items()
                if table_name not in STRICT_RECREATE_TABLES
            },
        )
        results = {}

        for table_name, schema_sql in SCHEMAS.items():
            try:
                self.db.execute(schema_sql)
                verify_table_schema(self.db, table_name, schema_sql)
                if table_name in STRICT_SE_STORAGE_TABLES:
                    from src.importer.importer import verify_se_storage_schema

                    verify_se_storage_schema(self.db, table_name)
                if table_name in STRICT_WE_STORAGE_TABLES:
                    from src.importer.importer import verify_we_storage_schema

                    verify_we_storage_schema(self.db, table_name)
                if table_name in STRICT_JC_STORAGE_TABLES:
                    from src.importer.importer import verify_jc_storage_schema

                    verify_jc_storage_schema(self.db, table_name)
                logger.debug(f"Created table: {table_name}")
                results[table_name] = True
            except Exception as e:
                logger.error(f"Failed to create table {table_name}: {e}")
                results[table_name] = False

        try:
            from src.importer.importer import verify_ck_coupled_tables

            verify_ck_coupled_tables(self.db, "NL_CK")
        except Exception as e:
            logger.error(f"Failed to verify coupled CK tables: {e}")
            for table_name in STRICT_RECREATE_TABLES:
                results[table_name] = False

        success_count = sum(1 for v in results.values() if v)
        logger.info(f"Successfully created {success_count}/{len(SCHEMAS)} tables")
